    <h1 class="doc-title">Beranda Siswa</h1>
    <p class="doc-lead">Halaman pertama setelah Anda login — biodata, status akun, dan jadwal pelajaran Anda hari ini.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Beranda Siswa merangkum hal-hal penting yang harus Anda ketahui hari ini tanpa membuka banyak menu.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Hanya <strong>Siswa</strong>. Guru dan wali murid tidak dapat membuka halaman ini.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Login sebagai siswa.</li>
        <li>Akun Anda terhubung ke data siswa (bila tidak, halaman menampilkan peringatan dan Anda diarahkan ke admin sekolah).</li>
        <li>Tahun ajaran &amp; semester aktif tersedia (untuk jadwal hari ini).</li>
    </ul>

    <h2 id="langkah">Bagian-bagian halaman</h2>

    <figure class="doc-figure">
        <img src="/img/docs/beranda-siswa.png" alt="Beranda Siswa" class="doc-shot">
        <figcaption><strong>Gambar 1</strong> — Beranda Siswa: biodata Anda, status akun, dan jadwal pelajaran hari ini.</figcaption>
    </figure>

    <h3>1. Kartu biodata (kiri)</h3>
    <p>Nama, NISN/NIS, tahun ajaran &amp; semester aktif, kelas, jurusan, <strong>wali kelas</strong>, tahun masuk, dan <strong>status</strong> Anda (<code>Aktif</code>/<code>Lulus</code>/<code>Pindah</code>/<code>Keluar</code>).</p>

    <h3>2. Kartu akun (kanan atas)</h3>
    <p><strong>Username</strong> dan <strong>Status Akun</strong> (mis. <em>Sudah ganti password</em>). Tombol <strong>Ganti password</strong> membuka halaman pengaturan akun.</p>

    <h3>3. Jadwal hari ini</h3>
    <p>Tabel <strong>Jam Ke · Waktu · Kelas · Mata Pelajaran · Guru</strong> untuk hari ini. Bila kosong, halaman menampilkan <em>"Tidak ada jadwal hari ini"</em> beserta tautan ke Jadwal Siswa untuk melihat jadwal mingguan. Tombol <strong>Lihat semua jadwal</strong> membuka menu Jadwal Siswa.</p>

    <h2 id="status">Arti status</h2>
    <ul>
        <li><code>Aktif</code> — Anda terdaftar aktif pada tahun ajaran berjalan.</li>
        <li><em>Sudah ganti password</em> — kewajiban ganti password sudah dipenuhi.</li>
    </ul>

    <h2 id="contoh">Contoh penggunaan</h2>
    <p>Andre login jam 06.45: melihat jurusannya IPA, wali kelasnya Bu Sari, dan jadwal hari ini jam 2–3 (Bahasa Inggris, lalu Biologi). Ia langsung tahu guru mana yang mengajar tanpa membuka menu jadwal.</p>

