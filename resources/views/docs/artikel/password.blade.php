    <h1 class="doc-title">Mengganti Password &amp; Kewajiban Ganti Password</h1>
    <p class="doc-lead">Password Anda harus diganti secara berkala atau saat administrator sekolah mengharuskan.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Password yang kuat melindungi akun Anda dan data sekolah. Kewajiban ganti password memastikan akun yang diberikan ke Anda segera dialihkan menjadi rahasia Anda sendiri.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Seluruh pengguna yang sudah login.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Anda sudah login.</li>
        <li>Anda mengetahui <strong>password lama</strong> Anda (kecuali yang diwajibkan ganti pada login pertama — lihat di bawah).</li>
    </ul>

    <h2 id="langkah">Langkah-langkah</h2>

    <figure class="doc-figure">
        <img src="/img/docs/login.png" alt="Halaman login" class="doc-shot">
        <figcaption><strong>Gambar 1</strong> — Bila akun wajib ganti password, Anda diarahkan ke formulir ganti password sesaat setelah login.</figcaption>
    </figure>

    <h3>Ganti password dari profil</h3>
    <ol>
        <li>Klik foto profil Anda di pojok kanan atas.</li>
        <li>Pilih <strong>Setting</strong>.</li>
        <li>Gulir ke bagian <strong>Ganti Password</strong>.</li>
        <li>Isi <strong>Password Lama</strong>, lalu <strong>Password Baru</strong> dua kali.</li>
        <li>Klik <strong>Simpan</strong>.</li>
    </ol>

    <h3>Ganti password saat diwajibkan</h3>
    <ol>
        <li>Setelah login, Anda langsung diarahkan ke halaman ganti password.</li>
        <li>Isi <strong>Password Lama</strong> (password yang diberikan administrator).</li>
        <li>Isi <strong>Password Baru</strong> dua kali.</li>
        <li>Klik <strong>Simpan</strong>, lalu masuk kembali.</li>
    </ol>

    <h2 id="status">Ketentuan password</h2>
    <ul>
        <li>Minimal 8 karakter.</li>
        <li>Sebaiknya kombinasi huruf besar, huruf kecil, angka, dan simbol.</li>
        <li>Password bersifat <strong>rahasia</strong> — administrator tidak dapat melihat password Anda.</li>
    </ul>

    <h2 id="contoh">Contoh penggunaan</h2>
    <p><strong>Siswa baru</strong> menerima password sementara dari sekolah. Saat login pertama, ia diwajibkan mengganti password. <strong>Admin</strong> mereset password siswa yang lupa — password sementara diberikan lewat cara yang aman (bukan SMS/WA), lalu siswa menggantinya saat login.</p>

