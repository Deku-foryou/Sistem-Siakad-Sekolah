    <h1 class="doc-title">Login, Logout &amp; Pengaturan Profil</h1>
    <p class="doc-lead">Cara masuk ke SIAKAD, keluar dengan aman, dan mengelola profil Anda.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Login memverifikasi identitas Anda. Logout memutus sesi agar akun tidak disalahgunakan. Pengaturan profil memungkinkan Anda mengubah data kontak yang tampil di aplikasi.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Seluruh pengguna yang sudah memiliki akun.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Username dan password diberikan oleh administrator sekolah.</li>
        <li>Akun Anda berstatus <strong>aktif</strong>.</li>
        <li>Kode <strong>Captcha</strong> tampak dengan jelas (bila tidak, klik tombol refresh).</li>
    </ul>

    <h2 id="langkah">Langkah-langkah</h2>

    <figure class="doc-figure">
        <img src="/img/docs/login.png" alt="Halaman login SIAKAD" class="doc-shot">
        <figcaption><strong>Gambar 1</strong> — Halaman login. Isi Username, Password, dan Captcha, lalu klik <strong>Log in</strong>.</figcaption>
    </figure>

    <h3>Login</h3>
    <ol>
        <li>Buka alamat aplikasi di browser Anda.</li>
        <li>Isi <strong>Username</strong> (mis. <code>siswa.20260001</code> atau <code>nama.anda</code>).</li>
        <li>Isi <strong>Password</strong> (huruf besar/kecil diperhatikan).</li>
        <li>Isi kode <strong>Captcha</strong>.</li>
        <li>Klik tombol <strong>Log in</strong>.</li>
    </ol>

    <h3>Logout</h3>
    <ol>
        <li>Klik foto profil/nama Anda di pojok kanan atas.</li>
        <li>Pilih <strong>Logout</strong>.</li>
        <li>Anda akan kembali ke halaman login.</li>
    </ol>
    <p class="doc-note doc-note-info"><i class="fa-solid fa-circle-info" aria-hidden="true"></i> Selalu gunakan <strong>Logout</strong>, terutama pada komputer bersama. Menutup browser saja tidak selalu memutus sesi.</p>

    <h3>Mengubah profil</h3>
    <ol>
        <li>Klik foto profil Anda di pojok kanan atas.</li>
        <li>Pilih <strong>Setting</strong>.</li>
        <li>Ubah <strong>Nama</strong> dan/atau <strong>Email</strong>, lalu klik <strong>Simpan</strong>.</li>
    </ol>

    <h2 id="status">Arti status akun</h2>
    <table class="doc-table">
        <thead><tr><th>Status</th><th>Arti</th></tr></thead>
        <tbody>
            <tr><td>Aktif</td><td>Akun dapat login dan menggunakan fitur.</td></tr>
            <tr><td>Nonaktif</td><td>Akun tidak dapat login; ditetapkan administrator.</td></tr>
        </tbody>
    </table>

    <h2 id="contoh">Contoh penggunaan</h2>
    <p><strong>Siswa</strong> baru login dengan password sementara dari sekolah, lalu diminta mengganti password pada login pertama. <strong>Admin</strong> mengatur profilnya dengan nama lengkap dan email resmi sekolah.</p>

