    <h1 class="doc-title">Keamanan Akun &amp; Pembatasan Akses</h1>
    <p class="doc-lead">Beberapa tindakan dapat dibatasi oleh sekolah demi keamanan bersama — ini bukan error, melainkan perlindungan.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Pembatasan akses mencegah penyalahgunaan: akun dicuri, data berubah liar, dan rahasia bocor. SIAKAD menerapkan tiga lapisan pembatasan:</p>
    <ol>
        <li><strong>Hak akses per peran</strong> — Anda hanya melihat halaman yang sesuai peran.</li>
        <li><strong>Batasan percobaan login</strong> — terlalu banyak gagal login memblokir sementara.</li>
        <li><strong>Wajib ganti password</strong> — akun baru diwajibkan mengganti password awal.</li>
    </ol>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Semua pengguna — tetapi Anda tidak dapat menaikkan tingkat akses Anda sendiri.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Kredensial (username &amp; password) yang diberikan administrator.</li>
    </ul>

    <h2 id="langkah">Langkah-langkah</h2>
    <ol>
        <li>Logout bila selesai menggunakan aplikasi, terutama di komputer umum.</li>
        <li>Jangan berbagi kredensial Anda kepada siapa pun — termasuk teman atau keluarga.</li>
        <li>Gunakan password yang kuat dan berbeda dengan akun lain (email, media sosial).</li>
        <li>Laporkan ke administrator bila mencurigai akun Anda disalahgunakan (mis. ada perubahan yang tidak Anda lakukan).</li>
    </ol>

