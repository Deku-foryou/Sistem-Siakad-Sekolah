    <h2 id="contoh">Contoh penggunaan</h2>
    <p><strong>Siswa</strong> mencoba membuka halaman input nilai melalui URL langsung — ditolak karena bukan halamannya. <strong>Wali</strong> yang mencoba membuka data siswa lain — ditolak. <strong>Admin</strong> yang salah menebak password 10 kali — akun diblokir sementara.</p>

