    <h1 class="doc-title">Notifikasi: Fungsi &amp; Cara Menggunakannya</h1>
    <p class="doc-lead">Melihat notifikasi penting dari aplikasi — pengumuman, keuangan, dan aktivitas lain yang berkenaan dengan Anda.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Notifikasi memberi tahu hal-hal yang perlu Anda ketahui tanpa harus membuka semua menu: pengumuman terbit, verifikasi penting, atau kejadian lain sesuai peran Anda.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Semua pengguna yang login.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul><li>Login ke aplikasi.</li></ul>

    <h2 id="langkah">Langkah-langkah</h2>
    <h3>Melihat notifikasi</h3>
    <ol>
        <li>Klik ikon <strong>lonceng</strong> di pojok kanan atas (dengan badge jumlah belum dibaca), <em>atau</em> buka menu <strong>Notifikasi</strong>.</li>
        <li>Halaman Notifikasi menampilkan tab <strong>Semua</strong> dan <strong>Belum dibaca</strong>.</li>
        <li>Gunakan filter <strong>Jenis</strong> untuk menyaring (mis. pengumuman, keuangan, dsb.).</li>
    </ol>

    <h3>Menandai telah dibaca</h3>
    <ol>
        <li>Klik tombol <strong>Tandai Dibaca</strong> pada satu notifikasi, <em>atau</em></li>
        <li>Klik <strong>Tandai Semua Dibaca</strong> untuk mengosongkan badge.</li>
    </ol>

    <h3>Membuka detail</h3>
    <p>Bila notifikasi memiliki tautan (<em>"Lihat detail →"</em>), klik untuk membuka halaman terkait (mis. pengumuman atau tagihan). Tautan di luar aplikasi tidak akan dibuka.</p>

