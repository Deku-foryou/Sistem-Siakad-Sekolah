    <h2 id="contoh">Contoh penggunaan</h2>
    <p>Sekolah menerbitkan pengumuman penting → semua siswa menerima notifikasi → siswa membuka lonceng, membaca, lalu menekan Tandai Semua Dibaca.</p>

