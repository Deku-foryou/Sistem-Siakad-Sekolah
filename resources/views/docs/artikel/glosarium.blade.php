    <h1 class="doc-title">Glosarium &amp; Kamus Data</h1>
    <p class="doc-lead">Istilah yang dipakai di SIAKAD dari A sampai Z, dan kamus singkat data untuk setiap peran.</p>

    <p class="doc-note doc-note-info"><i class="fa-solid fa-circle-info" aria-hidden="true"></i> Glosarium ini menjelaskan istilah <strong>untuk pengguna</strong>, bukan struktur teknis. Untuk struktur data lengkap (tabel, kolom, relasi), lihat <a href="/welcome-docs/artikel/referensi-tabel">Referensi Data</a>.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Memahami istilah yang muncul di menu, status, dan pesan aplikasi tanpa harus bertanya ke teknisi.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Semua pengguna yang sudah login.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul><li>Login ke aplikasi.</li></ul>

