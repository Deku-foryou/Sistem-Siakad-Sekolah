    <h2 id="contoh">Kamus berdasarkan peran</h2>
    <p><strong>Superadmin/Admin:</strong> pahami tarif, beasiswa, tagihan, status pembayaran, alokasi, saldo, refund, rekonsiliasi.</p>
    <p><strong>Guru:</strong> pahami penugasan mengajar, komponen nilai, bobot, KKTP, nilai akhir, finalisasi.</p>
    <p><strong>Siswa:</strong> pahami konteks akademik, jadwal, absensi, rapor, tagihan.</p>
    <p><strong>Wali:</strong> pahami relasi (pending → verified), periode berlaku, dan tab akademik/keuangan anak.</p>

