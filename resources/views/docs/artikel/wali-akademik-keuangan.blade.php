    <p class="doc-note doc-note-info"><i class="fa-solid fa-circle-info" aria-hidden="true"></i> Tab keuangan hanya menampilkan data anak yang relasinya terverifikasi. Untuk membayar tagihan, gunakan tombol <strong>Bayar</strong> yang tersedia di tab keuangan — pembayaran dicatat sebagai pembayaran dengan identitas Anda sebagai wali.</p>

    <h2 id="status">Arti data yang ditampilkan</h2>
    <ul>
        <li><strong>Hanya relasi terverifikasi</strong> — tanpa itu tab akademik/keuangan tidak bisa dibuka.</li>
        <li><strong>Periode</strong> — relasi dapat berakhir pada tanggal tertentu; setelah itu data tidak lagi tampil.</li>
        <li><strong>Rapor hanya final</strong> — tab Nilai/Rapor menampilkan rapor yang sudah difinalisasi.</li>
    </ul>

    <h2 id="contoh">Contoh penggunaan</h2>
    <p>Wali Sari membuka tab <em>Ketidakhadiran</em> dengan filter bulan berjalan: terlihat dua hari izin dan satu hari sakit. Ia lalu membuka tab <em>Keuangan</em>, melihat tagihan SPP November lunas, tagihan UAS belum lunas, dan membayar lewat tombol Bayar.</p>

