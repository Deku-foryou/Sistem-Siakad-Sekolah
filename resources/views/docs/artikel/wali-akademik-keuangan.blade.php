    <h1 class="doc-title">Wali: Mengakses Akademik &amp; Keuangan Anak</h1>
    <p class="doc-lead">Melihat nilai, absensi, jadwal, dan keuangan anak Anda — setelah relasi diverifikasi.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Portal wali memberikan gambaran perkembangan anak: nilai/rapor, kehadiran, catatan wali kelas, dan — bila sekolah mengaktifkan modul keuangan — tagihan serta pembayaran.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p><strong>Wali murid</strong> dengan relasi terverifikasi. Superadmin/admin melihat antrian, bukan isi akademik anak (sesuai pemisahan tugas).</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Login sebagai wali.</li>
        <li>Relasi dengan anak tersebut <strong>terverifikasi</strong> dan periode masih berlaku.</li>
    </ul>

    <h2 id="langkah">Langkah-langkah</h2>
