    <h1 class="doc-title">Profil Saya (Siswa)</h1>
    <p class="doc-lead">Biodata lengkap Anda yang tersimpan di sekolah — bersifat baca saja.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Halaman <strong>Profil Saya</strong> menampilkan seluruh data diri Anda yang dipakai sekolah: biodata, kontak, keluarga, dan status akademik. Halaman ini <strong>hanya dapat dibaca</strong> — tidak bisa diubah dari aplikasi.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Hanya <strong>Siswa</strong>.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul><li>Login sebagai siswa.</li></ul>

    <h2 id="langkah">Bagian-bagian halaman</h2>

    <figure class="doc-figure">
        <img src="/img/docs/profil-siswa.png" alt="Profil Saya" class="doc-shot">
        <figcaption><strong>Gambar 1</strong> — Profil Saya (data contoh/demo): identitas, informasi pribadi, kontak &amp; keluarga, dan status akun. NIK ditampilkan tersamar.</figcaption>
    </figure>

    <h3>1. Kepala profil</h3>
    <p>Nama, NIS/NISN, tahun ajaran &amp; semester aktif, kelas, jurusan, wali kelas, dan <strong>status</strong> (<code>Aktif</code>).</p>

    <h3>2. Informasi Pribadi</h3>
    <p><strong>NIK</strong> (ditampilkan tersamar — hanya 4 digit akhir), <strong>Tempat/Tanggal Lahir</strong>, <strong>Jenis Kelamin</strong>, <strong>Agama</strong>, <strong>Tahun Masuk</strong>, <strong>Asal Sekolah</strong>.</p>

    <h3>3. Kontak &amp; Keluarga</h3>
    <p><strong>Alamat</strong>, <strong>Telepon</strong>, <strong>Email</strong>, data <strong>Ayah/Ibu/Wali</strong>, dan <strong>Telepon Orang Tua/Wali</strong>.</p>

    <h3>4. Informasi Akun</h3>
    <p><strong>Username</strong> dan <strong>Status Password</strong> (mis. <em>Sudah diganti</em>), beserta tombol <strong>Pengaturan Akun</strong> bila perlu mengganti password atau email.</p>

    <p class="doc-note doc-note-info"><i class="fa-solid fa-circle-info" aria-hidden="true"></i> <strong>Halaman ini bersifat baca saja.</strong> Bila ada data yang salah/belum terisi, hubungi admin sekolah — pengajuan perubahan dilakukan lewat admin, bukan dari halaman ini.</p>

