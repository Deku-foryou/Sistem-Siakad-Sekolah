    <h2 id="contoh">Contoh penggunaan</h2>
    <p>Andre membuka Profil Saya untuk mencetak biodata pendaftaran lomba: ia melihat kelas (X IPA 1), jurusan (IPA), dan tahun masuknya (2026). Email keluarganya belum terisi — ia melaporkan ke admin sekolah.</p>

