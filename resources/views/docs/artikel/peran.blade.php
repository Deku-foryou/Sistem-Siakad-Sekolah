    <h1 class="doc-title">Peran Pengguna: Superadmin, Admin, Guru, Siswa &amp; Wali</h1>
    <p class="doc-lead">Setiap akun di SIAKAD adalah salah satu dari lima peran. Peran menentukan menu, halaman, dan tindakan yang boleh Anda lihat dan lakukan.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Peran membagi pekerjaan di aplikasi. <strong>Anda tidak bisa memilih peran sendiri</strong> — peran ditentukan administrator saat akun dibuat. Anda tidak bisa mengubah peran Anda sendiri dari dalam aplikasi.</p>

    <h2 id="pengguna">Detail peran</h2>
    <h3>Superadmin</h3>
    <p>Peran dengan kewenangan tertinggi. Mengelola: pengguna, data akademik (siswa, guru, kelas, mapel, jurusan, tahun ajaran, semester, jadwal), penilaian dan finalisasi rapor, pengumuman, seluruh modul keuangan (tarif, tagihan, pembayaran, refund, denda, rekonsiliasi), dan pengaturan aplikasi.</p>

    <h3>Admin</h3>
    <p>Peran operasional. Saat ini kewenangannya terfokus pada pengelolaan akun wali murid dan antrean verifikasi relasi wali dengan siswa. Admin <strong>tidak</strong> mengelola data akademik siswa, tidak menginput nilai, dan tidak menerbitkan rapor.</p>

    <h3>Guru</h3>
    <p>Mengajar. Guru melihat beranda guru, jadwal mengajarnya, mengisi absensi (harian dan/atau per jam), dan menginput/mengoreksi nilai pada kelas dan mapel yang ditugaskan.</p>

    <h3>Siswa</h3>
    <p>Melihat informasi dirinya: beranda siswa, profil, jadwal pelajaran, histori absensi (harian &amp; per jam), rapor, pengumuman, notifikasi, dan — bila sekolah mengaktifkan fitur keuangan — tagihan serta pembayaran.</p>

    <h3>Wali murid</h3>
    <p>Memonitor anak/anaknya. Setelah relasi wali–siswa <strong>diverifikasi admin</strong>, wali dapat melihat profil anak, jadwal, absensi, rapor, pengumuman, notifikasi, tagihan, dan melakukan pembayaran.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Anda memiliki akun aktif.</li>
        <li>Untuk wali murid: relasi wali–siswa sudah diverifikasi admin sebelum informasi akademik anak dapat diakses.</li>
    </ul>

    <h2 id="langkah">Langkah-langkah</h2>
    <ol>
        <li>Pertama, tentukan peran Anda berdasarkan akun yang diberikan sekolah.</li>
        <li>Login ke aplikasi.</li>
        <li>Setelah masuk, perhatikan halaman dan menu yang muncul — itu adalah area kerja peran Anda.</li>
        <li>Jika ada menu yang ingin dibuka tetapi tidak muncul, berarti bukan untuk peran Anda.</li>
    </ol>

