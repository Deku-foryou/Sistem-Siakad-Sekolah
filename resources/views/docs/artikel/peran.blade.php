    <h2 id="contoh">Contoh penggunaan</h2>
    <p><strong>Wali baru</strong> membuat akun, mengajukan relasi dengan anaknya, menunggu verifikasi admin, baru kemudian dapat melihat tagihan SPP dan nilai rapor anaknya. <strong>Guru baru</strong> menunggu penugasan mengajar dari superadmin, baru kemudian nilai dan absensi kelasnya muncul.</p>

