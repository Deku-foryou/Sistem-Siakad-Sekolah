    <h1 class="doc-title">Membaca Pengumuman (Siswa)</h1>
    <p class="doc-lead">Informasi resmi dari sekolah — dan cara memastikan Anda tidak melewatkannya.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Halaman <strong>Pengumuman</strong> (siswa) menampilkan seluruh pengumuman resmi yang ditujukan kepada publik atau ke kelas/jurusan/Anda secara khusus.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Hanya <strong>Siswa</strong>. Wali murid melihat pengumuman pada portal walinya; guru &amp; superadmin membaca dari beranda/notifikasi masing-masing.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul><li>Login sebagai siswa.</li></ul>

    <h2 id="langkah">Langkah-langkah</h2>

    <figure class="doc-figure">
        <img src="/img/docs/pengumuman-siswa.png" alt="Pengumuman Siswa" class="doc-shot">
        <figcaption><strong>Gambar 1</strong> — Halaman Pengumuman siswa: tab Pengumuman Aktif dan Riwayat Pengumuman.</figcaption>
    </figure>

    <ol>
        <li>Buka menu <strong>Pengumuman</strong> pada sidebar.</li>
        <li>Tab <strong>Pengumuman Aktif</strong> menampilkan yang masih berlaku; tab <strong>Riwayat Pengumuman</strong> menampilkan yang sudah berakhir/arsip.</li>
        <li>Klik <strong>Baca selengkapnya</strong> untuk membuka detail pengumuman.</li>
        <li>Pengumuman yang Anda baca otomatis tercatat <strong>sudah dibaca</strong>.</li>
    </ol>

    <h3>Setiap kartu pengumuman menampilkan</h3>
    <ul>
        <li><strong>Judul</strong> — judul pengumuman.</li>
        <li><strong>Isi singkat</strong> — beberapa baris pertama.</li>
        <li><strong>Kategori</strong> — mis. <code>akademik</code>, <code>acara</code>, <code>penting</code>, <code>darurat</code>.</li>
        <li><strong>Periode tayang</strong> — tanggal berlaku dari–sampai.</li>
    </ul>

    <h2 id="status">Arti status yang Anda lihat</h2>
    <ul>
        <li><strong>Tampil di tab aktif</strong> — pengumuman masih berlaku dan ditujukan ke Anda.</li>
        <li><strong>Tidak ditampilkan</strong> — pengumuman sudah berakhir, diarsipkan, atau bukan untuk kelas/jurusan/Anda.</li>
        <li><strong>Prioritas tinggi/mendesak</strong> (bila dilabeli sekolah) — baca lebih dahulu.</li>
    </ul>
    <p class="doc-note doc-note-info"><i class="fa-solid fa-circle-info" aria-hidden="true"></i> Pengumuman yang terbit juga menghasilkan <strong>notifikasi</strong> — pantau ikon lonceng agar tidak ketinggalan.</p>

    <h2 id="contoh">Contoh penggunaan</h2>
    <p>Senin pagi Andre melihat pengumuman <em>"Simulasi Ujian Tengah Semester Ganjil"</em> (kategori akademik, berlaku sampai 12/12/2026). Ia klik Baca selengkapnya, mencatat tanggal UTS, dan mulai belajar.</p>

