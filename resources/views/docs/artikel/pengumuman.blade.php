        </tbody>
    </table>

    <h2 id="contoh">Contoh penggunaan</h2>
    <p>Menjelang ujian: superadmin membuat pengumuman kategori <code>akademik</code>, prioritas <code>tinggi</code>, target semua, berlaku 2 minggu → Terbitkan → seluruh siswa &amp; wali menerima notifikasi dan melihat pengumuman di beranda.</p>

