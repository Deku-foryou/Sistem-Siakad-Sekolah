    <h1 class="doc-title">Membuat, Menerbitkan &amp; Mengarsipkan Pengumuman</h1>
    <p class="doc-lead">Menyusun pengumuman untuk seluruh sekolah atau sasaran tertentu — dari draf hingga tayang dan arsip.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Pengumuman adalah saluran resmi sekolah untuk informasi umum: akademik, acara, penting, atau darurat. Pengumuman yang diterbitkan juga menghasilkan notifikasi bagi penerima.</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <ul>
        <li><strong>Membuat &amp; menerbitkan</strong>: Superadmin (menu <em>Pengumuman</em>).</li>
        <li><strong>Membaca</strong>: seluruh pengguna sesuai sasaran (menu <em>Pengumuman Siswa</em> untuk siswa; juga tampil di beranda siswa &amp; wali).</li>
    </ul>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul>
        <li>Login sebagai Superadmin.</li>
        <li>Isi dan target pengumuman sudah dipersiapkan.</li>
    </ul>

    <h2 id="langkah">Langkah-langkah</h2>
    <h3>Membuat pengumuman</h3>
    <ol>
        <li>Buka menu <strong>Pengumuman</strong>.</li>
        <li>Klik <strong>Tambah Pengumuman</strong>.</li>
        <li>Isi <strong>Judul</strong> dan <strong>Isi</strong>.</li>
        <li>Pilih <strong>Kategori</strong>: <code>akademik</code> / <code>acara</code> / <code>penting</code> / <code>darurat</code>.</li>
        <li>Pilih <strong>Prioritas</strong>: <code>rendah</code> / <code>sedang</code> / <code>tinggi</code> / <code>mendesak</code>.</li>
        <li>Pilih <strong>Target</strong>: <code>semua</code> / <code>jurusan</code> / <code>kelas</code> / <code>siswa</code> — bila bukan semua, pilih sasaran spesifiknya.</li>
        <li>Isi <strong>Berlaku Dari</strong> dan <strong>Berlaku Sampai</strong> bila perlu.</li>
        <li>Klik <strong>Simpan Draf</strong> atau langsung <strong>Terbitkan</strong>.</li>
    </ol>

    <h3>Menerbitkan pengumuman</h3>
    <ol>
        <li>Pada daftar pengumuman berstatus draf, klik <strong>Terbitkan</strong>.</li>
        <li>Konfirmasi tayang — penerima sesuai target akan menerima notifikasi.</li>
        <li>Status berubah menjadi <code>terbit</code>.</li>
    </ol>

    <h3>Mengarsipkan pengumuman</h3>
    <ol>
        <li>Pada pengumuman berstatus terbit, klik <strong>Arsipkan</strong>.</li>
        <li>Riwayat baca (siapa sudah membaca) tetap dipertahankan.</li>
    </ol>

    <h3>Detail &amp; riwayat baca</h3>
    <p>Klik <strong>Detail</strong> pada baris pengumuman untuk melihat isi lengkap dan daftar penerima beserta status bacanya.</p>

