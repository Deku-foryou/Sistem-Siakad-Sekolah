    <h1 class="doc-title">Pusat Bantuan &amp; Cara Melapor Masalah</h1>
    <p class="doc-lead">Cara mencari solusi di dokumentasi ini, dan cara melaporkan masalah ke sekolah dengan informasi yang cukup.</p>

    <h2 id="tujuan">Tujuan fitur</h2>
    <p>Memastikan masalah Anda terselesaikan secepat mungkin — oleh Anda sendiri (dokumentasi) atau oleh orang yang tepat (admin/pengelola).</p>

    <h2 id="pengguna">Siapa yang dapat menggunakan</h2>
    <p>Semua pengguna yang sudah login.</p>

    <h2 id="prasyarat">Prasyarat</h2>
    <ul><li>Login.</li></ul>

    <h2 id="langkah">Langkah-langkah</h2>
    <h3>1. Cari dulu di dokumentasi</h3>
    <ol>
        <li>Gunakan <strong>kotak pencarian</strong> di bagian atas dokumentasi — ketik gejala atau istilah (mis. "captcha", "tagihan belum lunas", "rapor final").</li>
        <li>Telusuri kategori di sidebar kiri.</li>
        <li>Buka artikel <a href="/welcome-docs/artikel/troubleshooting">Masalah Umum &amp; Solusinya</a> — sebagian besar pertanyaan sudah dijawab di sana.</li>
    </ol>

    <h3>2. Catat informasi penting</h3>
    <ul>
        <li>Halaman/menu tempat masalah terjadi.</li>
        <li>Pesan error <strong>persis</strong> (salin apa adanya).</li>
        <li>Username Anda (jangan pernah kirim password).</li>
        <li>Waktu kejadian dan langkah yang Anda lakukan sebelum masalah muncul.</li>
        <li>Tangkapan layar bila memungkinkan.</li>
    </ul>

    <h3>3. Laporkan ke pihak yang tepat</h3>
    <table class="doc-table">
        <thead><tr><th>Jenis masalah</th><th>Hubungi</th></tr></thead>
        <tbody>
            <tr><td>Akun, password, terkunci</td><td>Tata usaha / admin sekolah</td></tr>
            <tr><td>Data siswa/guru salah</td><td>Admin sekolah (superadmin)</td></tr>
            <tr><td>Tagihan/pembayaran keliru</td><td>Tata usaha keuangan / bendahara</td></tr>
            <tr><td>Nilai/rapor</td><td>Wali kelas / guru mata pelajaran</td></tr>
            <tr><td>Aplikasi error, lambat, tidak bisa dibuka</td><td>Admin/pengelola aplikasi</td></tr>
        </tbody>
    </table>
    <p class="doc-note doc-note-warn"><i class="fa-solid fa-triangle-exclamation" aria-hidden="true"></i> <strong>Jangan pernah:</strong> mengirim password melalui WA/email; meminjamkan akun; melaporkan tanpa pesan error yang jelas.</p>

    <h3>4. Setelah masalah selesai</h3>
    <p>Beri tahu pelapor bahwa masalah sudah ditangani (bila Anda admin yang menangani), atau pastikan aplikasi berjalan normal kembali.</p>

    <h2 id="status">Arti status tiket (bila sekolah memakai pencatatan terpisah)</h2>
    <p>SIAKAD tidak memiliki modul tiket bawaan; pelaporan/pencatatan insiden dikelola sekolah sesuai SOP masing-masing.</p>

    <h2 id="contoh">Contoh laporan yang baik</h2>
    <p><em>"Saya Sari (username: sari.guru) membuka menu Absensi Per Jam jam 10.15. Saat klik Simpan muncul pesan 'Batas edit guru (H+1) terlewat'. Pertemuan Selasa 10 Nov jam ke-3. Mohon dibantu."</em></p>
    <p>Bandingkan dengan laporan buruk: <em>"absensi error, tolong diperbaiki."</em></p>

